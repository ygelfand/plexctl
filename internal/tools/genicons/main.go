package main

import (
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"net/http"
	"os"
	"sort"
	"strconv"
	"strings"
	"unicode/utf8"

	"golang.org/x/net/html"
)

const (
	cheatSheetURL = "https://www.nerdfonts.com/cheat-sheet"
	outputFile    = "pkg/nerdfonts/icons.go"
)

func main() {
	fmt.Println("Fetching Nerd Fonts cheat sheet...")
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run() (runErr error) {
	resp, err := http.Get(cheatSheetURL)
	if err != nil {
		return fmt.Errorf("fetch cheat sheet: %w", err)
	}
	defer func() {
		if err := resp.Body.Close(); err != nil {
			runErr = errors.Join(runErr, fmt.Errorf("close cheat sheet response: %w", err))
		}
	}()
	if resp.StatusCode != http.StatusOK {
		return fmt.Errorf("fetch cheat sheet: %s", resp.Status)
	}

	body, err := io.ReadAll(resp.Body)
	if err != nil {
		return fmt.Errorf("read cheat sheet: %w", err)
	}

	script, err := findGlyphScript(string(body))
	if err != nil {
		return err
	}
	icons, err := parseGlyphs(script)
	if err != nil {
		return err
	}
	return generateGoFile(outputFile, icons)
}

func generateGoFile(path string, glyphs map[string]string) error {
	var source strings.Builder
	source.WriteString("package nerdfonts\n\n// Code generated by internal/tools/genicons. DO NOT EDIT.\n\nvar Icons = map[string]string{\n")

	keys := make([]string, 0, len(glyphs))
	for k := range glyphs {
		keys = append(keys, k)
	}
	sort.Strings(keys)

	for _, k := range keys {
		char, err := hexToChar(glyphs[k])
		if err != nil {
			return fmt.Errorf("convert glyph %q: %w", k, err)
		}
		fmt.Fprintf(&source, "\t%q: %q,\n", k, char)
	}

	source.WriteString("}\n")
	if err := os.WriteFile(path, []byte(source.String()), 0o644); err != nil {
		return fmt.Errorf("write icons: %w", err)
	}
	return nil
}

func findGlyphScript(htmlData string) (string, error) {
	doc, err := html.Parse(strings.NewReader(htmlData))
	if err != nil {
		return "", fmt.Errorf("parse cheat sheet HTML: %w", err)
	}

	var scriptContent string
	var f func(*html.Node)
	f = func(n *html.Node) {
		if n.Type == html.ElementNode && n.Data == "script" && n.FirstChild != nil {
			if strings.Contains(n.FirstChild.Data, "const glyphs") {
				scriptContent = n.FirstChild.Data
				return
			}
		}
		for c := n.FirstChild; c != nil; c = c.NextSibling {
			f(c)
		}
	}
	f(doc)
	if scriptContent == "" {
		return "", errors.New("could not find Nerd Font glyphs object in HTML")
	}
	return scriptContent, nil
}

func parseGlyphs(js string) (map[string]string, error) {
	start := strings.Index(js, "{")
	end := strings.LastIndex(js, "}")
	if start == -1 || end < start {
		return nil, errors.New("could not find glyph object literal")
	}
	obj := js[start : end+1]
	obj = removeTrailingComma(obj)
	var glyphs map[string]string
	if err := json.Unmarshal([]byte(obj), &glyphs); err != nil {
		return nil, fmt.Errorf("parse glyph object: %w", err)
	}
	return glyphs, nil
}

func removeTrailingComma(js string) string {
	lastBrace := strings.LastIndex(js, "}")
	if lastBrace == -1 {
		return js
	}

	i := lastBrace - 1
	for i >= 0 && (js[i] == ' ' || js[i] == '\t' || js[i] == '\n' || js[i] == '\r') {
		i--
	}

	if i >= 0 && js[i] == ',' {
		js = js[:i] + js[i+1:]
	}

	return js
}

func hexToChar(value string) (string, error) {
	codepoint, err := strconv.ParseUint(value, 16, 32)
	if err != nil {
		return "", fmt.Errorf("parse code point %q: %w", value, err)
	}
	r := rune(codepoint)
	if !utf8.ValidRune(r) {
		return "", fmt.Errorf("invalid Unicode code point %q", value)
	}
	return string(r), nil
}
